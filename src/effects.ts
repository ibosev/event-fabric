import { createCommand, uuidv7 } from "./id.js";
import type { CommandInput } from "./id.js";
import type { Metadata, OutboxEntry, ScheduleChange, StreamId } from "./types.js";
import { toJson } from "./validation.js";
import { assertScheduleName } from "./schedules.js";
import { parseProcessGroup } from "./internal.js";

/** The Command or Event whose handling records the effects. */
export type Cause = {
  id: string;
  correlationId: string;
  metadata: Metadata;
  traceparent?: string;
};
export type EffectOptions = { notBefore?: string; replaceKey?: string };
export type QueueOptions = EffectOptions & {
  metadata?: Metadata;
  suffix?: string;
  queue?: string;
  idempotencyKey?: string;
  /** A Saga's own Saga Message (a Workflow's `ask` step) the Worker replies with; the reply goes to this instance. */
  replyTo?: string;
  /** The Workflow run a reply must name. */
  run?: string;
};
export type MessageRouting = {
  /** The Worker queue for a Message type; throws when no Worker handles it. */
  queue(name: string): string;
  /** Checks a Message before it is committed, e.g. against its Worker's schema. */
  check?(entry: OutboxEntry): Promise<void>;
};

/**
 * Records the Commands and Messages one cause leaves through the Outbox. Every
 * effect inherits the cause's Metadata, Correlation and trace; a Message's
 * Idempotency key is derived from `source` (Consumer group or Aggregate), the
 * `instance` (a Saga instance id, when the recorder serves one), the cause id
 * and a per-call suffix: by default the effect's position among this
 * recorder's effects.
 */
export function recordEffects(
  cause: Cause,
  source: string,
  options: { now?: Date; routing?: MessageRouting; instance?: string; owner?: StreamId } = {},
) {
  const now = options.now ?? new Date(),
    timestamp = now.toISOString();
  const outbox: OutboxEntry[] = [];
  const schedules: ScheduleChange[] = [];
  const inherited = {
    causationId: cause.id,
    correlationId: cause.correlationId,
    ...(cause.traceparent ? { traceparent: cause.traceparent } : {}),
  };
  const metadata = (extra?: Metadata) =>
    toJson({ ...cause.metadata, ...extra }, "Metadata");
  const effects = {
    outbox,
    schedules,
    schedule(name: string, dueAt: string | Date, input: CommandInput) {
      checkName(name);
      const owner = options.owner;
      if (
        !owner ||
        input.stream.context !== owner.context ||
        input.stream.aggregate !== owner.aggregate ||
        input.stream.id !== owner.id
      )
        throw new Error("A Schedule must target its owning Stream");
      if (input.id !== undefined)
        throw new Error("Schedule attempt ids are generated by EventFabric");
      if (
        !(dueAt instanceof Date) &&
        (typeof dueAt !== "string" || !/T.*(?:Z|[+-]\d\d:\d\d)$/i.test(dueAt))
      )
        throw new Error("Schedule due time must be an instant with a timezone");
      const due = new Date(dueAt).toISOString();
      effects.tell(input, { notBefore: due });
      const entry = outbox.at(-1)!;
      entry.message = { ...entry.message, schedule: { name, dueAt: due } };
      schedules.push({ name, entry });
    },
    cancelSchedule(name: string) {
      checkName(name);
      if (!options.owner)
        throw new Error("A Schedule must have an owning Stream");
      schedules.push({ name });
    },
    tell(input: CommandInput & EffectOptions, settings: EffectOptions = {}) {
      const {
        notBefore = settings.notBefore,
        replaceKey = settings.replaceKey,
        ...command
      } = input;
      outbox.push({
        id: uuidv7(now.getTime()),
        kind: "command",
        message: createCommand({
          ...command,
          payload: toJson(command.payload ?? {}, "Payload"),
          metadata: metadata(command.metadata),
          ...inherited,
          timestamp,
        }),
        notBefore,
        replaceKey,
      });
    },
    queue(
      type: string | { name: string },
      payload: any,
      settings: QueueOptions = {},
    ) {
      const name = typeof type === "string" ? type : type.name;
      const { replyTo } = settings;
      const process = parseProcessGroup(source);
      if (replyTo !== undefined && (options.instance === undefined || !process))
        throw new Error("Only a Saga Reaction can ask a Worker to reply");
      const id = uuidv7(now.getTime());
      const suffix = settings.suffix ?? String(outbox.length);
      outbox.push({
        id,
        kind: "message",
        queue: settings.queue,
        notBefore: settings.notBefore,
        replaceKey: settings.replaceKey,
        message: {
          id,
          name,
          payload: toJson(payload ?? {}, "Payload"),
          metadata: metadata(settings.metadata),
          schemaVersion: 1,
          ...inherited,
          timestamp,
          idempotencyKey:
            settings.idempotencyKey ??
            JSON.stringify(
              options.instance === undefined
                ? [source, cause.id, suffix]
                : [source, options.instance, cause.id, suffix],
            ),
          attempt: 1,
          ...(replyTo === undefined || !process
            ? {}
            : process.kind === "workflow"
              ? {
                  replyTo: {
                    workflow: process.name,
                    instance: options.instance!,
                    step: replyTo,
                    ...(settings.run === undefined ? {} : { run: settings.run }),
                  },
                }
              : { replyTo: { saga: process.name, instance: options.instance!, name: replyTo } }),
        },
      });
    },
    /** Routes every Message to its Worker and runs the checks; call once, before commit. */
    async seal(checkMetadata: (metadata: Metadata) => Promise<void>) {
      for (const entry of outbox) {
        if (entry.kind === "message") {
          const routed = options.routing?.queue(entry.message.name);
          entry.queue ??= routed ?? entry.message.name;
        }
        await checkMetadata(entry.message.metadata);
        await options.routing?.check?.(entry);
      }
      return outbox;
    },
  };
  function checkName(name: string) {
    assertScheduleName(name);
    if (schedules.some((change) => change.name === name))
      throw new Error("A Command can change a Schedule only once");
  }
  return effects;
}
export type Effects = ReturnType<typeof recordEffects>;
